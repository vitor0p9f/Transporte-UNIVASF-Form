"""Loading helper for the scenario CSVs.

The scenarios that run are the sum of two files in the project root, read in
this order:

    scenarios.csv       generated by scripts/generate_scenarios.py (arqueti)
    scenarios_base.csv  fixed setup of the ``base`` instance -- hand-written,
                        not sampled (see the generator docstring)

Both use the same columns (see SCENARIO_FIELDS in
``scripts/generate_scenarios.py``). By default, rows whose instance has no
``distance.csv`` on disk are dropped -- the same filter the runners
(`main.py`, `scripts/run_all.py`) already applied.
"""

import csv
from pathlib import Path

#: Scenario files summed together, in order.
SCENARIO_FILES = ("scenarios.csv", "scenarios_base.csv")


def parse_node_labels(value: object) -> tuple[int, ...] | None:
    """Read a semicolon-separated node field, e.g. ``"43;44;45"``.

    Used by the ``origin`` column (origins the draft may use) and the
    ``destination_labels`` column (destinations the pair may end at). An empty
    or missing field means "free" (None), not "no node".
    """
    if value is None:
        return None
    ids = [item.strip() for item in str(value).split(";") if item.strip()]
    return tuple(int(item) for item in ids) or None


def load_scenarios(
    root: str | Path,
    files: tuple[str, ...] = SCENARIO_FILES,
    require_matrices: bool = True,
) -> list[dict]:
    """Read and sum the scenario files that exist under `root`.

    Args:
        root: Project root (where the CSVs live).
        files: File names, in read order.
        require_matrices: Drop scenarios whose instance has no `distance.csv`.

    Returns:
        Scenario rows (dicts) in file order; missing files are simply skipped.
    """
    root = Path(root)
    scenarios: list[dict] = []
    for name in files:
        path = root / name
        if not path.exists():
            continue
        with path.open(newline="", encoding="utf-8") as f:
            scenarios.extend(csv.DictReader(f))
    if require_matrices:
        scenarios = [
            s for s in scenarios
            if (root / "instances" / s["instance_id"] / "distance.csv").exists()
        ]
    return scenarios
